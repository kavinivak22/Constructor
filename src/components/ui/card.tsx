import * as React from "react"

import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => {
  const isGlass = className?.includes("glass-card") || className?.includes("glass");
  return (
    <div
      ref={ref}
      className={cn(
        isGlass ? "" : "rounded-2xl border bg-card text-card-foreground shadow-sm hover:shadow-md transition-shadow duration-200",
        className
      )}
      {...props}
    />
  );
})
Card.displayName = "Card"

